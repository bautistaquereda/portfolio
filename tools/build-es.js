// Generates es/index.html (Spanish version) from index.html + i18n.js.
// Run it after editing index.html or i18n.js:   node tools/build-es.js
// Google indexes /es/ as its own page, already in Spanish in the HTML.

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.join(__dirname, "..");
const SITE = "https://bautistaquereda.dev";
const BIRTH_YEAR = 2002; // same rule as script.js: +1 every August 1st

const ctx = {};
vm.runInNewContext(fs.readFileSync(path.join(ROOT, "i18n.js"), "utf8") + ";this.I18N = I18N;", ctx);
const ES = ctx.I18N.es;
const EN = ctx.I18N.en;
const t = (key) => ES[key] ?? EN[key] ?? "";

const now = new Date();
const age = now.getFullYear() - BIRTH_YEAR - (now.getMonth() < 7 ? 1 : 0);
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const escAttr = (s) => esc(s).replace(/"/g, "&quot;");

let html = fs.readFileSync(path.join(ROOT, "index.html"), "utf8");

function replaceOnce(from, to) {
  if (!html.includes(from)) throw new Error("Not found in index.html: " + from);
  html = html.replace(from, to);
}

// Replaces the inner content of every element carrying `attr="key"`.
function replaceContents(attr, render) {
  const re = new RegExp(`<([a-zA-Z0-9]+)\\b[^>]*\\s${attr}="([^"]+)"[^>]*>`, "g");
  let out = "", last = 0, m;
  while ((m = re.exec(html))) {
    const [openTag, tag, key] = m;
    const start = m.index + openTag.length;
    // find the matching closing tag (handles nested tags of the same name)
    const tagRe = new RegExp(`<(/?)${tag}\\b[^>]*>`, "g");
    tagRe.lastIndex = start;
    let depth = 1, end = -1, tm;
    while ((tm = tagRe.exec(html))) {
      depth += tm[1] ? -1 : 1;
      if (depth === 0) { end = tm.index; break; }
    }
    if (end < 0) throw new Error(`No closing </${tag}> for ${key}`);
    out += html.slice(last, start) + render(key);
    last = end;
    re.lastIndex = end;
  }
  html = out + html.slice(last);
}

replaceContents("data-i18n", (key) => esc(t(key).replace("{age}", age)));
replaceContents("data-i18n-html", (key) => t(key));
html = html.replace(/(<[^>]*\sdata-i18n-title="([^"]+)"[^>]*)>/g, (all, tag, key) =>
  /\stitle="/.test(tag) ? all : `${tag} title="${escAttr(t(key))}">`
);

// <head>: language, title, description, canonical, previews
replaceOnce('<html lang="en">', '<html lang="es">');
replaceOnce('var PAGE_LANG = "en";', 'var PAGE_LANG = "es";');
html = html.replace(/<title>[^<]*<\/title>/, `<title>${esc(t("meta.title"))}</title>`);
for (const name of ['name="description"', 'property="og:description"', 'name="twitter:description"']) {
  html = html.replace(new RegExp(`(<meta ${name} content=")[^"]*(")`), `$1${escAttr(t("meta.description"))}$2`);
}
for (const name of ['property="og:title"', 'name="twitter:title"']) {
  html = html.replace(new RegExp(`(<meta ${name} content=")[^"]*(")`), `$1${escAttr(t("meta.title"))}$2`);
}
replaceOnce(`<link rel="canonical" href="${SITE}/"`, `<link rel="canonical" href="${SITE}/es/"`);
replaceOnce(`<meta property="og:url" content="${SITE}/"`, `<meta property="og:url" content="${SITE}/es/"`);
replaceOnce('<meta property="og:locale" content="en_US" />', '<meta property="og:locale" content="es_AR" />');
replaceOnce('<meta property="og:locale:alternate" content="es_AR" />', '<meta property="og:locale:alternate" content="en_US" />');

html = html.replace(
  "<!doctype html>",
  "<!doctype html>\n<!-- Generated by tools/build-es.js from index.html + i18n.js. Do not edit by hand. -->"
);

fs.mkdirSync(path.join(ROOT, "es"), { recursive: true });
fs.writeFileSync(path.join(ROOT, "es", "index.html"), html);
console.log("es/index.html generated");
